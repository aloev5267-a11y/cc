const CYRILLIC_RE = /[а-яё]/i

// Нормализует название города, пришедшее от гео-сервиса, к русскому виду.
// Возвращает корректное русское название или null, если уверенно сопоставить
// не удалось (тогда лучше ничего не предлагать, чем показать неверный город).
export function normalizeCityToRussian(raw: string | null | undefined): string | null {
  if (!raw) return null
  const trimmed = raw.trim()
  if (!trimmed) return null

  // Уже на кириллице — берём как есть.
  if (CYRILLIC_RE.test(trimmed)) return trimmed

  const key = trimmed.toLowerCase()
  return EN_TO_RU[key] ?? null
}
